int main() {
    int s;
    s = 0;
    if (1 < 2 && 2 < 3) s = s + 1;
    if (1 > 2 || 3 > 2) s = s + 2;
    if (1 != 2) s = s + 4;
    if (!(1 == 2)) s = s + 8;
    if (3 <= 3) s = s + 16;
    if (3 >= 3) s = s + 32;
    if (2 >= 3) s = s + 64;
    if (5) s = s + 128;
    return s;
}
